function interpolate(
  text: string,
  values?: Record<string, string | number | boolean>,
): string {
  if (!values) return text;
  return text.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    values[key] === undefined ? match : String(values[key]),
  );
}

export function translateText(
  locale: UiLocale,
  text: string,
  values?: Record<string, string | number | boolean>,
): string {
  if (locale !== "en" || !text.trim()) return interpolate(text, values);
  if (en[text]) return interpolate(en[text], values);
  return interpolate(text, values);
}

interface I18nValue {
  locale: UiLocale;
  t: (text: string, values?: Record<string, string | number | boolean>) => string;
}

const fallback: I18nValue = {
  locale: "zh-CN",
  t: (text, values) => interpolate(text, values),
};

const I18nContext = createContext<I18nValue>(fallback);

export function I18nProvider({
  preference,
  children,
}: {
  preference: UiLocalePreference;
  children: ReactNode;
}) {
  const locale: UiLocale = preference === "auto" ? hostLocale : preference;
  const value = useMemo<I18nValue>(
    () => ({
      locale,
      t: (text, values) => translateText(locale, text, values),
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

export function preferenceFromSettings(values: {
  uiLocale?: UiLocalePreference;
}): UiLocalePreference {
  return values.uiLocale ?? "auto";
}
